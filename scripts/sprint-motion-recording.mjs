import { homedir } from 'node:os';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { mkdirSync, writeFileSync, statSync } from 'node:fs';
import assert from 'node:assert/strict';
const { chromium } = await import(pathToFileURL(resolve(homedir(),'.codex/skills/develop-web-game/node_modules/playwright/index.mjs')).href);
const out=resolve(process.argv[2] || 'artifacts/implementation-sprint/motion');
mkdirSync(out,{recursive:true});
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1440,height:900},recordVideo:{dir:out,size:{width:1440,height:900}}});
const page=await context.newPage(), events=[];
const started=Date.now();
async function action(name,fn,duration=1000) { events.push({name,seconds:(Date.now()-started)/1000});await fn();await page.waitForTimeout(duration); }
await page.goto('http://127.0.0.1:3101/');
for(const [name,duration] of [['Delegate Research',1300],['Delegate further',1500],['Trace Scraper',900],['Preview Research revoke',1100],['Confirm demo revoke',1700],['Inspect authority in Command',1300]]) await action(name,()=>page.getByRole('button',{name,exact:true}).click(),duration);
assert.match(await page.locator('.local-state').innerText(),/ACTIVE[\s\S]*BLOCKED/);
await action('Blocked Scraper proof',()=>page.getByRole('button',{name:'Attempt demo spend',exact:true}).click(),800);
await action('Surviving Operations',()=>page.getByRole('button',{name:'Select Operations',exact:true}).click(),750);
await action('Open Arena',()=>page.getByRole('link',{name:'Arena',exact:true}).click(),400);
for(const [name,duration] of [['Fund demo mission',1000],['Submit 3 demo results',1000]]) await action(name,()=>page.getByRole('button',{name,exact:true}).click(),duration);
await action('Inspect Submission A',()=>page.locator('.contender').filter({has:page.getByText('Submission A',{exact:true})}).click(),600);
await action('Explicit simulated settlement',()=>page.getByRole('button',{name:'Select A & settle in demo',exact:true}).click(),1700);
const winner=await page.locator('.mission-outcome').innerText();
await action('Inspect another submission; recorded winner stays A',()=>page.locator('.contender').filter({has:page.getByText('Submission C',{exact:true})}).click(),900);
assert.equal(await page.locator('.mission-outcome').innerText(),winner);
events.push({name:'Stillness',seconds:(Date.now()-started)/1000});
const video=page.video();await context.close();await video.saveAs(resolve(out,'interaction-qa.webm'));await browser.close();
assert(statSync(resolve(out,'interaction-qa.webm')).size > 100000, 'Recording must contain encoded frames');
writeFileSync(resolve(out,'events.json'),JSON.stringify(events,null,2));
console.log(JSON.stringify(events));
